// fakeHelp serves fixed help text keyed by the joined command path.
type fakeHelp map[string]string

// Help returns the fixed help text or fails for an unknown command path.
func (f fakeHelp) Help(binary string, args []string) (string, error) {
	text, ok := f[strings.Join(append([]string{binary}, args...), " ")]
	if !ok {
		return "", errors.New("unknown command path")
	}
	return text, nil
}

// smokePath is the command path the sample help belongs to.
const smokePath = "dkim2ctl smoke"

const sampleHelp = `Run checks

Usage:
  dkim2ctl smoke [flags]

Flags:
      --expect-ready   expected readiness state (default true)
  -h, --help           help for smoke

Global Flags:
      --server-url string   canonical loopback daemon URL (default "http://127.0.0.1:8080")
`

// TestRenderPageEmbedsHelpSections proves usage and flag blocks come from
// the help text and are escaped for roff.
func TestRenderPageEmbedsHelpSections(t *testing.T) {
	template := ".TH X 1\n.SH SYNOPSIS\n" + directivePrefix + "Usage dkim2ctl smoke\n" +
		".SH OPTIONS\n" + directivePrefix + "Flags dkim2ctl smoke\n" +
		directivePrefix + "Global_Flags dkim2ctl smoke\n"
	page, err := renderPage("dkim2ctl.1", []byte(template), fakeHelp{smokePath: sampleHelp})
	if err != nil {
		t.Fatalf("renderPage: %v", err)
	}
	text := string(page)
	for _, want := range []string{
		".\\\" Code generated by mangen from docs/man/src/dkim2ctl.1.in; DO NOT EDIT.\n",
		".ti -4n\n\\fBdkim2ctl\\fR smoke [flags]\n",
		".TP\n\\fB\\-\\-expect\\-ready\\fR\nexpected readiness state (default true)\n",
		".TP\n\\fB\\-h\\fR, \\fB\\-\\-help\\fR\nhelp for smoke\n",
		".TP\n\\fB\\-\\-server\\-url\\fR \\fIstring\\fR\n",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("page lacks %q:\n%s", want, text)
		}
	}
	if strings.Contains(text, "@cobra") {
		t.Errorf("directive survived rendering:\n%s", text)
	}
}

// TestRenderPageFailsClosed proves malformed directives and help drift stop
// generation instead of emitting a partial page.
func TestRenderPageFailsClosed(t *testing.T) {
	help := fakeHelp{smokePath: sampleHelp, "dkim2ctl": "Usage:\n  dkim2ctl\n\nFlags:\nnot a flag line\n"}
	for name, template := range map[string]string{
		"unknown binary":     directivePrefix + "Usage sh\n",
		"flag-like argument": directivePrefix + "Usage dkim2ctl --help\n",
		"missing section":    directivePrefix + "Commands dkim2ctl smoke\n",
		"unsupported":        directivePrefix + "Run dkim2ctl smoke\n",
		"unknown path":       directivePrefix + "Usage dkim2ctl fixture\n",
		"bad flag line":      directivePrefix + "Flags dkim2ctl\n",
		"non-ascii":          ".SH NAME\nd\u00e9j\u00e0\n",
		"short directive":    directivePrefix + "Usage\n",
	} {
		if _, err := renderPage("x.1", []byte(template), help); err == nil {
			t.Errorf("%s: renderPage accepted the template", name)
		}
	}
}

// TestRoffLineGuardsControlCharacters proves text cannot become a request.
func TestRoffLineGuardsControlCharacters(t *testing.T) {
	if got := roffLine(`.so /etc/passwd \n`); got != `\&.so /etc/passwd \en` {
		t.Fatalf("roffLine = %q", got)
	}
}

// TestCheckDetectsStaleAndOrphanPages proves the stale check covers changed
// pages and pages without a template.
func TestCheckDetectsStaleAndOrphanPages(t *testing.T) {
	root := t.TempDir()
	generator := &pageGenerator{
		sourceDir: filepath.Join(root, "src"),
		outputDir: root,
		help:      fakeHelp{smokePath: sampleHelp},
	}
	if err := os.Mkdir(generator.sourceDir, 0o755); err != nil {
		t.Fatal(err)
	}
	source := ".TH X 1\n" + directivePrefix + "Usage dkim2ctl smoke\n"
	if err := os.WriteFile(filepath.Join(generator.sourceDir, "dkim2ctl.1.in"), []byte(source), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := generator.check(); !errors.Is(err, errStalePages) {
		t.Fatalf("missing page: check = %v", err)
	}
	if err := generator.write(); err != nil {
		t.Fatalf("write: %v", err)
	}
	if err := generator.check(); err != nil {
		t.Fatalf("fresh pages: check = %v", err)
	}
	if err := os.WriteFile(filepath.Join(root, "orphan.8"), []byte(".TH O 8\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := generator.check(); !errors.Is(err, errStalePages) {
		t.Fatalf("orphan page: check = %v", err)
	}
}
